export function translate(message, language = 'en') {
  if (language === 'id' || typeof message !== 'string') return message
  if (english[message]) return english[message]
  return message
    .replace(/^Belum ada stok atau metadata sesuai filter untuk: (.*)\. Ubah kebutuhan atau filter rating\.$/, 'No stock or matching metadata for: $1. Adjust your needs or rating filter.')
    .replace(/^Batas bawah biaya kebutuhan wajib Rp(.*)\. Coba anggaran lebih besar atau kurangi kebutuhan wajib; batas ini belum menjamin kombinasi layak\.$/, 'The lower bound for required items is IDR $1. Increase the budget or reduce required categories; this bound does not guarantee feasibility.')
}

export function presetGoal(goal, language) {
  const goals = ['Siapkan perlengkapan awal kuliah', 'Rapikan meja belajar di kos', 'Siapkan kebutuhan harian kos']
  const id = goals.find(value => value === goal || english[value] === goal)
  return id ? translate(id, language) : goal
}
