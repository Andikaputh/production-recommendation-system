"""Generate all public metric summaries from evaluation.json; --check is a drift gate."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- evaluation:begin -->", "<!-- evaluation:end -->"
TARGETS = ["README.md", "docs/model/model-card.md", "docs/product-requirements.md", "docs/problem-validation.md"]


def summary(data: dict) -> str:
    rank = data["ranking"]["EXP-006"]
    basket = data["baskets"]["EXP-007"]
    return "\n".join([
        BEGIN,
        f"Single source: `artifacts/reports/evaluation.json`, run **{data['generated_at']}**, dataset `{data['dataset_version']}` (synthetic), model `{data['model_version']}`, seed {data['seed']}.",
        "",
        "| Measure | Result | Population |", "| --- | ---: | --- |",
        f"| NDCG@10 EXP-006 | {rank['metrics']['ndcg@10']:.4f} | {rank['n_users']} eligible users |",
        f"| Recall@10 EXP-006 | {rank['metrics']['recall@10']:.4f} | same users |",
        f"| Feasibility EXP-007 | {basket['budget_feasibility_rate']:.2%} | {basket['n_missions']} synthetic missions |",
        f"| Required category coverage | {basket['required_category_coverage']:.2%} | feasible results only |",
        f"| Solver p95 | {basket['solver_latency_ms']['p95']:.2f} ms | this run environment, not an SLA |",
        "",
        "Generated by `python scripts/sync_evaluation_docs.py`; `--check` detects drift. See `docs/reports/benchmark-report.md` and `docs/model/evaluation-audit.md`. Offline results do not validate business impact or represent a live user experiment.", END,
    ])


def sync(check=False):
    path = ROOT / "artifacts/reports/evaluation.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    block = summary(data)
    dirty = []
    for target in TARGETS:
        output = ROOT / target
        before = output.read_text(encoding="utf-8")
        if BEGIN in before:
            after = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, before, flags=re.S)
        else:
            after = before.rstrip() + "\n\n## Synchronized evaluation results\n\n" + block + "\n"
        if before != after:
            dirty.append(target)
            if not check:
                output.write_text(after, encoding="utf-8")
    provenance = data.get("provenance", {})
    if not provenance:
        raise ValueError("evaluation.json belum memiliki provenance; jalankan evaluasi baru dahulu.")
    print(json.dumps({"source_sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "changed": dirty, "checked": check}))
    if check and dirty:
        raise SystemExit(1)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    sync(parser.parse_args().check)
